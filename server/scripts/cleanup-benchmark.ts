/**
 * cleanup-benchmark.ts
 * 
 * Purge ALL benchmark / generated / dummy data from the production workspace.
 * 
 * Usage:
 *   npx tsx server/scripts/cleanup-benchmark.ts
 * 
 * This script is idempotent — safe to run multiple times.
 * It does NOT delete the benchmark generation scripts themselves.
 */

import { PrismaClient } from '@prisma/client';
import axios from 'axios';
import fs from 'fs';
import path from 'path';

const prisma = new PrismaClient();

const AI_SERVICE_URL = process.env.AI_SERVICE_URL || 'http://localhost:8000';

// ---------------------------------------------------------------------------
// Patterns that identify benchmark / generated filenames.
// These match the *original* filename stored in FileRecord.filename.
// ---------------------------------------------------------------------------
const BENCHMARK_FILENAME_PATTERNS: RegExp[] = [
  /^doc_\d+\.(pdf|docx|pptx|xlsx|png)$/i,
  /^code_\d+\.\w+$/i,
  /^note_\d+\.\w+$/i,
  /^test_document\.\w+$/i,
  /^resume1\.pdf$/i,
  /^resume_copy\.pdf$/i,
  /^image1\.png$/i,
  // Small benchmark helper files generated by benchmark.ts
  /^app\.ts$/i,
  /^utils\.js$/i,
];

function isBenchmarkFilename(filename: string): boolean {
  return BENCHMARK_FILENAME_PATTERNS.some(pattern => pattern.test(filename));
}

// ---------------------------------------------------------------------------
// Paths for on-disk benchmark directories
// ---------------------------------------------------------------------------
const ROOT_DIR = path.resolve(__dirname, '..', '..');
const BENCHMARK_DIRS = [
  path.join(ROOT_DIR, 'benchmark_data'),
  path.join(ROOT_DIR, 'benchmark_data_large'),
];

async function deleteDirectoryContents(dirPath: string): Promise<number> {
  if (!fs.existsSync(dirPath)) return 0;
  let count = 0;
  const entries = fs.readdirSync(dirPath);
  for (const entry of entries) {
    const fullPath = path.join(dirPath, entry);
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      count += await deleteDirectoryContents(fullPath);
      fs.rmdirSync(fullPath);
    } else {
      fs.unlinkSync(fullPath);
      count++;
    }
  }
  return count;
}

async function main() {
  console.log('=== NeuroDesk Benchmark Data Cleanup ===\n');

  // 1. Find all benchmark FileRecords in the database
  const allFiles = await prisma.fileRecord.findMany({
    select: { id: true, filename: true, path: true },
  });

  const benchmarkRecords = allFiles.filter(f => isBenchmarkFilename(f.filename));
  console.log(`Found ${benchmarkRecords.length} benchmark records in DB (out of ${allFiles.length} total).`);

  if (benchmarkRecords.length > 0) {
    const fileIds = benchmarkRecords.map(r => r.id);

    // 2. Delete ChromaDB embeddings for each benchmark file
    console.log('\nDeleting ChromaDB embeddings...');
    let chromaDeleted = 0;
    for (const fileId of fileIds) {
      try {
        await axios.delete(`${AI_SERVICE_URL}/internal/embed/file/${fileId}`);
        chromaDeleted++;
      } catch (err: any) {
        // Ignore 404 — already deleted or never indexed
        if (err?.response?.status !== 404) {
          console.warn(`  Warning: Failed to delete embeddings for ${fileId}: ${err.message}`);
        }
      }
    }
    console.log(`  Deleted embeddings for ${chromaDeleted} files.`);

    // 3. Delete FTS entries
    console.log('\nDeleting FTS entries...');
    try {
      // Ensure FTS table exists before attempting deletes
      await prisma.$executeRawUnsafe(`
        CREATE VIRTUAL TABLE IF NOT EXISTS file_search USING fts5(
          file_id UNINDEXED, filename, content, category,
          tokenize='porter unicode61'
        );
      `);
      for (const fileId of fileIds) {
        await prisma.$executeRawUnsafe(`DELETE FROM file_search WHERE file_id = ?`, fileId);
      }
      console.log(`  Deleted FTS entries for ${fileIds.length} files.`);
    } catch (err: any) {
      console.warn(`  Warning: FTS cleanup partially failed: ${err.message}`);
    }

    // 4. Delete Chunks from DB
    console.log('\nDeleting chunks from DB...');
    const chunkResult = await prisma.chunk.deleteMany({
      where: { fileId: { in: fileIds } },
    });
    console.log(`  Deleted ${chunkResult.count} chunks.`);

    // 5. Delete AICache entries related to benchmark files
    console.log('\nDeleting AI cache entries...');
    let cacheDeleted = 0;
    for (const fileId of fileIds) {
      const cacheResult = await prisma.aICache.deleteMany({
        where: { cacheKey: { contains: fileId } },
      });
      cacheDeleted += cacheResult.count;
    }
    console.log(`  Deleted ${cacheDeleted} cache entries.`);

    // 6. Delete Relationships involving benchmark files
    console.log('\nDeleting relationships...');
    const relResult1 = await prisma.relationship.deleteMany({
      where: { sourceFileId: { in: fileIds } },
    });
    const relResult2 = await prisma.relationship.deleteMany({
      where: { targetFileId: { in: fileIds } },
    });
    console.log(`  Deleted ${relResult1.count + relResult2.count} relationships.`);

    // 7. Delete FileAccessLog entries
    console.log('\nDeleting access logs...');
    const accessResult = await prisma.fileAccessLog.deleteMany({
      where: { fileId: { in: fileIds } },
    });
    console.log(`  Deleted ${accessResult.count} access log entries.`);

    // 8. Delete the on-disk uploaded files
    console.log('\nDeleting uploaded files from disk...');
    let diskDeleted = 0;
    for (const record of benchmarkRecords) {
      try {
        if (fs.existsSync(record.path)) {
          fs.unlinkSync(record.path);
          diskDeleted++;
        }
      } catch {
        // Non-critical — file may already be gone
      }
    }
    console.log(`  Deleted ${diskDeleted} files from disk.`);

    // 9. Delete the FileRecord entries from DB
    console.log('\nDeleting FileRecord entries from DB...');
    const fileResult = await prisma.fileRecord.deleteMany({
      where: { id: { in: fileIds } },
    });
    console.log(`  Deleted ${fileResult.count} FileRecord entries.`);
  }

  // 10. Clean up the on-disk benchmark directories
  console.log('\nCleaning benchmark directories on disk...');
  for (const dir of BENCHMARK_DIRS) {
    if (fs.existsSync(dir)) {
      const count = await deleteDirectoryContents(dir);
      console.log(`  ${dir}: deleted ${count} files.`);
    } else {
      console.log(`  ${dir}: does not exist, skipping.`);
    }
  }

  // Summary
  const remaining = await prisma.fileRecord.count();
  console.log(`\n=== Cleanup Complete ===`);
  console.log(`Remaining FileRecord entries: ${remaining}`);

  await prisma.$disconnect();
}

main().catch(err => {
  console.error('Cleanup failed:', err);
  process.exit(1);
});
